interface Props {
  notes: Record<string, string>;
  tasks: Record<string, Task[]>;
  moods: Record<string, number>;
  sleep: Record<string, SleepData>;
  range: 7 | 30;
  lang: Lang;
}

export default function AiInsights({ notes, tasks, moods, sleep, range, lang }: Props) {
  const l = L[lang] ?? L.en;
  const [enabled, setEnabled] = useStored<boolean>("dn.aiInsights", false);
  const [state, setState] = useState<{ range: number; items: string[] } | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const run = async () => {
    // Только числа по дням, без текстов и дат (день недели нужен для закономерностей вроде «по понедельникам хуже»)
    const today = todayISO();
    const days = [];
    for (let i = range - 1; i >= 0; i--) {
      const iso = shiftISO(today, -i);
      const dayTasks = tasks[iso] ?? [];
      const s = sleep[iso];
      days.push({
        wd: fromISO(iso).getDay(),
        mood: moods[iso],
        sleepH: s?.hours,
        sleepQ: s?.quality,
        done: dayTasks.filter((x) => x.done).length,
        total: dayTasks.length,
        words: countWords(notes[iso] ?? ""),
      });
    }
    if (days.filter((d) => d.mood !== undefined).length < 3) {
      setError(l.few);
      return;
    }
    setLoading(true);
    setError(null);
    // сервер укладывается в 45 с; клиент ждёт чуть дольше и показывает причину, а не вечную загрузку
    const ctl = new AbortController();
    const timer = setTimeout(() => ctl.abort(), 55_000);
    try {
      const r = await fetch("/api/insights", {
        signal: ctl.signal,
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ lang, days }),
      });
      const d = await r.json().catch(() => ({}));
      if (!r.ok || !Array.isArray(d?.insights)) throw Object.assign(new Error("bad"), { detail: d?.detail || d?.error || `HTTP ${r.status}` });
      setState({ range, items: d.insights });
    } catch (e) {
      const err = e as { detail?: string; name?: string };
      const detail = err.name === "AbortError" ? "timeout" : err.detail;
      setError(detail ? `${l.err} (${detail})` : l.err);
    } finally {
      clearTimeout(timer);
      setLoading(false);
    }
  };

  const btnCls = "flex h-9 shrink-0 items-center gap-1.5 rounded-lg border border-[var(--line)] bg-[var(--panel-2)] px-3 text-[12px] font-semibold text-[var(--ink-soft)] transition-all duration-150 hover:border-[var(--accent)] hover:text-[var(--accent-deep)] active:scale-95 disabled:opacity-60";

  return (
    <div className="mb-5 flex flex-col gap-2 rounded-xl border border-[var(--line)] bg-[var(--panel)] p-4" style={{ boxShadow: "var(--shadow-sm)" }}>
      <div className="flex items-center gap-2">
        <span className="text-[14.5px] font-bold">{l.title}</span>
        {enabled && (
          <button onClick={() => { setEnabled(false); setState(null); setError(null); }} className="ml-auto text-[12px] font-semibold text-[var(--ink-faint)] hover:text-[var(--ink)]">
            {l.disable}
          </button>
        )}
      </div>
      {!enabled ? (
        <>
          <p className="text-[13px] text-[var(--ink-soft)]">{l.off}</p>
          <p className="text-[12.5px] leading-relaxed text-[var(--ink-faint)]">{l.warn}</p>
          <div><button onClick={() => setEnabled(true)} className={btnCls}>{l.enable}</button></div>
        </>
      ) : (
        <>
          {loading ? (
            <div className="flex flex-col gap-2" role="status" aria-label={l.loading}>
              <div className="h-3.5 w-full animate-pulse rounded bg-[var(--hover)]" />
              <div className="h-3.5 w-3/4 animate-pulse rounded bg-[var(--hover)]" />
            </div>
          ) : state ? (
            <ul className="flex list-disc flex-col gap-1.5 pl-5 text-[13.5px] leading-relaxed text-[var(--ink-soft)]">
              {state.items.map((s, i) => <li key={i}>{s}</li>)}
            </ul>
          ) : null}
          {error && <p className="text-[12.5px] text-[var(--ink-soft)]">{error}</p>}
          <div className="flex flex-wrap items-center gap-2">
            <button onClick={run} disabled={loading} className={btnCls}>{state ? l.again : l.run}</button>
            <span className="text-[11.5px] text-[var(--ink-faint)]">{l.note}</span>
          </div>
        </>
      )}
    </div>
  );
}
